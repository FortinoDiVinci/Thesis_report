function J0E = J0E_3DOF(q)
%
%    J0E = J0E_3DOF(q1,q2,q3)

% Jacobian matrix of the youBot considering its 2nd,3rd and 4th joints

q1 = q(1);
q2 = q(2);
q3 = q(3);

t2 = cos(q1);
t3 = q1+q2;
t4 = cos(t3);
t5 = q3+t3;
t6 = sin(t3);
t7 = cos(t5);
t8 = sin(t5);
t9 = t4.*(2.7e+1./2.0e+2);
t11 = t4.*8.266365894244634e-18;
t13 = t6.*1.35e-1;
t10 = t7.*(1.09e+2./5.0e+2);
t12 = t7.*1.334865011070615e-17;
t14 = -t13;
t15 = t8.*2.18e-1;
t16 = -t15;
J0E = reshape([t14+t16-sin(q1).*1.55e-1,t2.*9.491012693391987e-18+t11+t12,t2.*(3.1e+1./2.0e+2)+t9+t10,0.0,-1.0,6.123233995736766e-17,t14+t16,t11+t12,t9+t10,0.0,-1.0,6.123233995736766e-17,t16,t12,t10,0.0,-1.0,6.123233995736766e-17],[6,3]);
