

for i = 1:3
    user(i).cond(1).stiff.data = impedance{i}.xi(1,:);
    user(i).cond(1).damp.data = impedance{i}.xi(2,:);
    user(i).cond(1).mass.data = impedance{i}.xi(3,:);
    user(i).cond(1).r2.data = impedance{i}.r2_pos;
    % idx selection
    idx_R2_s05{i} = user(i).cond(1).r2.data > 0.5;
    [~,idx_stiff_sMAD{i}] = rmoutliers(user(i).cond(1).stiff.data, 'ThresholdFactor', 5);
    idx_select{i} = idx_R2_s05{i} & ~idx_stiff_sMAD{i};
    % mean and std
    user(i).cond(1).stiff.mean = mean(user(i).cond(1).stiff.data(idx_select{i}));
    user(i).cond(1).stiff.std = std(user(i).cond(1).stiff.data(idx_select{i}));
    user(i).cond(1).damp.mean = mean(user(i).cond(1).damp.data(idx_select{i}));
    user(i).cond(1).damp.std = std(user(i).cond(1).damp.data(idx_select{i}));
    user(i).cond(1).mass.mean = mean(user(i).cond(1).mass.data(idx_select{i}));
    user(i).cond(1).mass.std = std(user(i).cond(1).mass.data(idx_select{i}));
    user(i).cond(1).r2.mean = mean(user(i).cond(1).r2.data(idx_select{i}));
end

